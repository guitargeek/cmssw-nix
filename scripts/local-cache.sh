#!/usr/bin/env bash
# Back the builds up to a binary cache on persistent storage.
#
#   ./scripts/local-cache.sh init    # one-time: signing key + substituter
#   ./scripts/local-cache.sh push    # after ./scripts/build.sh
#   ./scripts/local-cache.sh status
#
# Why this exists, and why it is not scripts/push-cache.sh: on this machine
# /nix/store is an overlay whose upper layer lives on an ephemeral disk. A VM
# reset reverts it to the base image, and everything built here disappears -
# gcroots included, because a gcroot only defends against the *collector*, not
# against the filesystem going away. That is how ~100 minutes of CMSSW builds
# were lost once already.
#
# /home is a different, persistent volume with over a terabyte free. Copying
# the closures there turns a reset from an afternoon of recompiling into a few
# minutes of decompression. push-cache.sh does the same thing to cachix, which
# is the right answer for sharing between machines but needs an account; this
# needs nothing.
set -euo pipefail

cd "$(dirname "$0")/.."

cache_dir=${CMSSW_NIX_CACHE:-/home/claude/cmssw-nix-cache}
key_dir=${XDG_CONFIG_HOME:-$HOME/.config}/nix
secret_key=$key_dir/cmssw-nix-cache.secret
public_key=$key_dir/cmssw-nix-cache.public
nix_conf=$key_dir/nix.conf
key_name=cmssw-nix-cache-1

# The releases, plus the two things that are in no release's runtime closure
# and that build.sh roots for exactly that reason: the CMSSW checkouts (~500 MB
# each, the slowest thing to refetch) and the dev shells' inputs, which is
# where Geant4's datasets live. result-geant4 and result-g4data stood in for
# the latter here by hand; nothing maintained them and one had gone dangling,
# so a store reset would have taken the datasets with it.
links=(result-10_6 result-20_1 result-src-10_6 result-src-20_1
       result-shell-10_6 result-shell-20_1)

die() { echo "$*" >&2; exit 1; }

cmd_init() {
  mkdir -p "$key_dir"

  # Create the whole binary-cache layout here, as the invoking user, rather
  # than letting the first push create it. A push goes through the nix daemon,
  # which runs as root and would create nar/ owned by root and mode 0755 - and
  # the NAR files themselves are then written by *this* user, which cannot
  # create anything inside it. The push appears to run, prints a "copying
  # path" line for everything, and leaves an empty cache behind.
  mkdir -p "$cache_dir/nar" "$cache_dir/log" "$cache_dir/realisations"
  [ -f "$cache_dir/nix-cache-info" ] || printf 'StoreDir: /nix/store\n' > "$cache_dir/nix-cache-info"

  if [ ! -f "$secret_key" ]; then
    echo "==> generating a signing key ($key_name)"
    # Sign what we push: /etc/nix/nix.conf currently sets require-sigs=false,
    # but that file is regenerated by NixOS and a reset can take the setting
    # with it. A signed cache stays usable either way.
    nix key generate-secret --key-name "$key_name" > "$secret_key"
    chmod 600 "$secret_key"
    nix key convert-secret-to-public < "$secret_key" > "$public_key"
  fi

  # ~/.config/nix survives a store reset because /home does; /etc/nix does not.
  local pub
  pub=$(cat "$public_key")
  touch "$nix_conf"
  if ! grep -q "$cache_dir" "$nix_conf"; then
    echo "==> adding $cache_dir as a substituter in $nix_conf"
    {
      echo "extra-substituters = file://$cache_dir"
      echo "extra-trusted-public-keys = $pub"
    } >> "$nix_conf"
  fi

  echo "cache      $cache_dir"
  echo "public key $pub"
}

# What gets pushed is whatever the out-links point at, and nothing keeps them
# in step with the flake: a build made with `nix build --no-link`, or one made
# before an edit under gen/, leaves result-<release> on an older store path.
# The push then copies that older path, verifies it, and reports success -
# while the build that was actually just made stays uncached and, worse,
# unpinned. That is how a finished 10_6 build sat unprotected for a day.
#
# Evaluating the flake is seconds against a push of gigabytes, so say which
# links are behind. It is a warning rather than an error: pushing an older
# build on purpose is legitimate, being unaware of it is not.
declare -A release_attrs=( [result-10_6]=cmssw_10_6_30 [result-20_1]=cmssw )

warn_stale_links() {
  local link want have stale=0
  for link in "${!release_attrs[@]}"; do
    [ -L "$link" ] || continue
    want=$(nix eval --raw ".#${release_attrs[$link]}.outPath" 2>/dev/null) || continue
    have=$(readlink -f "$link")
    [ "$want" = "$have" ] && continue
    echo "warning: $link does not point at what the flake evaluates to now" >&2
    echo "           link   $have" >&2
    echo "           flake  $want" >&2
    stale=1
  done
  [ "$stale" -eq 0 ] ||
    echo "run ./scripts/build.sh to refresh the out-links first, unless the older build is what you meant to push" >&2
}

cmd_push() {
  [ -f "$secret_key" ] || die "no signing key - run './scripts/local-cache.sh init' first"

  warn_stale_links

  local paths=()
  for link in "${links[@]}"; do
    [ -L "$link" ] || continue
    # A dangling out-link is exactly the post-reset state; skip rather than fail.
    local p
    p=$(readlink -f "$link") || continue
    [ -e "$p" ] || { echo "skipping $link (dangling)"; continue; }
    paths+=("$p")
  done
  [ ${#paths[@]} -gt 0 ] || die "nothing to push - run ./scripts/build.sh first"

  local before
  before=$(find "$cache_dir" -name '*.narinfo' 2>/dev/null | wc -l)

  echo "==> pushing runtime closures"
  nix copy --to "file://$cache_dir?secret-key=$secret_key" "${paths[@]}"

  # The runtime closure is not what makes a rebuild cheap: a rebuild starts
  # from the build inputs - compilers, ROOT, the generated sources - and those
  # are the hours. Push what the derivations were built from as well.
  echo "==> pushing build-time closures"
  local derivers=() d
  for p in "${paths[@]}"; do
    d=$(nix-store --query --deriver "$p") || continue
    [ -e "$d" ] && derivers+=("$d")
  done
  if [ ${#derivers[@]} -gt 0 ]; then
    mapfile -t build_paths < <(
      nix-store --query --requisites --include-outputs "${derivers[@]}" \
        | grep -v '\.drv$'
    )
    nix copy --to "file://$cache_dir?secret-key=$secret_key" "${build_paths[@]}"
  fi

  # nix copy reports success per path even when every write failed on a
  # permission error, so the push has to be verified rather than trusted.
  # Verify by presence, not by growth: a re-push of an unchanged tree
  # legitimately adds nothing, and counting narinfos cannot tell that apart
  # from a push where every write was denied.
  local missing=()
  for p in "${paths[@]}"; do
    local hash=${p#/nix/store/}
    hash=${hash%%-*}
    [ -f "$cache_dir/$hash.narinfo" ] || missing+=("$p")
  done
  if [ ${#missing[@]} -gt 0 ]; then
    echo "these paths are not in $cache_dir after the push:" >&2
    printf '  %s\n' "${missing[@]}" >&2
    echo "check the directory is writable by $(id -un) all the way down" >&2
    exit 1
  fi

  local after
  after=$(find "$cache_dir" -name '*.narinfo' 2>/dev/null | wc -l)
  if [ "$after" -gt "$before" ]; then
    echo "==> $((after - before)) new paths in the cache"
  else
    echo "==> cache already had everything"
  fi

  cmd_status
}

cmd_status() {
  if [ ! -d "$cache_dir" ]; then
    echo "no cache at $cache_dir"
    return
  fi
  printf 'cache   %s\n' "$cache_dir"
  printf 'size    %s\n' "$(du -sh "$cache_dir" | cut -f1)"
  printf 'nars    %s\n' "$(find "$cache_dir" -name '*.narinfo' | wc -l)"
  printf 'free    %s\n' "$(df -h --output=avail "$cache_dir" | tail -1 | tr -d ' ')"
}

case "${1:-push}" in
  init)   cmd_init ;;
  push)   cmd_push ;;
  status) cmd_status ;;
  *) die "usage: $0 {init|push|status}" ;;
esac
